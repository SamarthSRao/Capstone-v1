"""Regenerate the replay Jobs from deploy/nasa_replay.py and the CSV.

    python3 deploy/render_nasa_job.py

Writes two manifests from the same player and the same CSV:

  k8s/07-nasa-replay-job.yaml       Job nasa-replay: the whole morning, 3 loops.
  k8s/07b-fast-demo-replay-job.yaml Job fast-demo-replay: one pass from row
                                    FAST_START_OFFSET, for a live demo.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]

# Row 250 is where the 13 July morning starts to climb (about 92 RPS, then 132
# by row 255). Rows 226-249 are flat at 85-92 RPS. Starting at 226 gives the
# forecaster its 24-sample window of quiet history before the ramp, instead of
# four minutes of it. The rows still play at one per second.
FAST_START_OFFSET = 226


def block(text, indent):
    pad = " " * indent
    return "\n".join(pad + line if line else "" for line in text.splitlines())


HEADER = """# Not part of kustomization.yaml. Replays the NASA morning (10 compressed
# minutes, looped) so the forecast can lead the ramp:
#   ./deploy/load_gen.sh --replay
#   kubectl apply -f k8s/07-nasa-replay-job.yaml
# The CSV and player are the copies in deploy/. Regenerate this file with
#   python3 deploy/render_nasa_job.py
# if either one changes.
apiVersion: v1
kind: ConfigMap
metadata:
  name: nasa-replay
  namespace: capstone
data:
  nasa_replay.py: |
__SCRIPT__
  nasa_demo_window_10min.csv: |
__CSV__
---
# Indexed job: N pods run the same morning at the same time. Pod i sends
# round(target)/N (remainder on the lower indexes) so the cluster sees the
# full rate. Default 4 fits a 6 GB kind node. REPLAY_PARALLELISM in
# deploy/load_gen.sh rewrites the lines marked replay-parallelism and
# replay-shards before apply. Requests stay small so the pods still schedule
# on a 2 vCPU node; limits are what a busy shard may use if the node has it.
apiVersion: batch/v1
kind: Job
metadata:
  name: nasa-replay
  namespace: capstone
  labels:
    app: nasa-replay
spec:
  parallelism: 4 # replay-parallelism
  completions: 4 # replay-parallelism
  completionMode: Indexed
  backoffLimit: 1
  ttlSecondsAfterFinished: 600
  template:
    metadata:
      labels:
        app: nasa-replay
    spec:
      restartPolicy: Never
      containers:
        - name: replay
          image: python:3.12-slim
          imagePullPolicy: IfNotPresent
          command: ["python", "-u", "/replay/nasa_replay.py"]
          args:
            - --host
            - http://nginx-lb.capstone.svc.cluster.local:8090/
            - --csv
            - /replay/nasa_demo_window_10min.csv
            - --loops
            - "3"
            - --shards
            - "4" # replay-shards
          env:
            - name: REPLAY_SHARDS
              value: "4" # replay-shards
          resources:
            requests:
              cpu: 50m
              memory: 64Mi
            limits:
              cpu: 400m
              memory: 192Mi
          volumeMounts:
            - name: replay
              mountPath: /replay
              readOnly: true
      volumes:
        - name: replay
          configMap:
            name: nasa-replay
"""


FAST_COMMENT = """# Not part of kustomization.yaml. Live-demo version of 07-nasa-replay-job.yaml:
# the same player, the same CSV, the same 40x compression (one row per
# second), but one pass starting at row __OFFSET__, about 24 seconds before the
# morning starts to climb, so the first scale-up comes about a minute in
# instead of after four minutes of quiet. About __SECONDS__ seconds of traffic.
#   kubectl apply -f k8s/07b-fast-demo-replay-job.yaml
#   kubectl delete -f k8s/07b-fast-demo-replay-job.yaml   # afterwards
# Generated by python3 deploy/render_nasa_job.py; edit that, not this file.
"""


def fast_variant(rendered, csv_rows):
    """Rename the ConfigMap and Job and play one pass from FAST_START_OFFSET."""
    head, sep, body = rendered.partition("apiVersion: v1\n")
    assert sep, "HEADER layout changed"
    body = sep + body
    swaps = [
        ("  name: nasa-replay\n  namespace: capstone\ndata:", "  name: fast-demo-replay\n  namespace: capstone\ndata:"),
        ("  name: nasa-replay\n  namespace: capstone\n  labels:\n    app: nasa-replay", "  name: fast-demo-replay\n  namespace: capstone\n  labels:\n    app: fast-demo-replay"),
        ("      labels:\n        app: nasa-replay", "      labels:\n        app: fast-demo-replay"),
        ('            - --loops\n            - "3"', '            - --loops\n            - "1"\n            - --start-offset\n            - "%d"' % FAST_START_OFFSET),
        ("            name: nasa-replay\n", "            name: fast-demo-replay\n"),
    ]
    for old, new in swaps:
        assert body.count(old) == 1, "expected one %r" % old
        body = body.replace(old, new)
    comment = FAST_COMMENT.replace("__OFFSET__", str(FAST_START_OFFSET)).replace(
        "__SECONDS__", str(csv_rows - FAST_START_OFFSET)
    )
    return comment + body


def main():
    script = (ROOT / "deploy" / "nasa_replay.py").read_text()
    csv_text = (ROOT / "deploy" / "nasa_demo_window_10min.csv").read_text()
    rendered = HEADER.replace("__SCRIPT__", block(script, 4)).replace("__CSV__", block(csv_text, 4))
    if not rendered.endswith("\n"):
        rendered += "\n"
    dest = ROOT / "k8s" / "07-nasa-replay-job.yaml"
    dest.write_text(rendered)
    print("wrote %s" % dest)
    csv_rows = len([line for line in csv_text.splitlines() if line.strip()]) - 1
    if not 0 <= FAST_START_OFFSET < csv_rows:
        raise SystemExit("FAST_START_OFFSET %d is outside the %d-row CSV" % (FAST_START_OFFSET, csv_rows))
    fast = ROOT / "k8s" / "07b-fast-demo-replay-job.yaml"
    fast.write_text(fast_variant(rendered, csv_rows))
    print("wrote %s" % fast)


if __name__ == "__main__":
    main()
